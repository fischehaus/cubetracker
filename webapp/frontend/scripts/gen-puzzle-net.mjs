// Dev-Generator (cubing.js als Oracle). Erzeugt Baked-Data pro piece-basiertem
// Puzzle: Facelet-Geometrie (aus generatesvg) + Move-Token-Transforms (aus
// applyAlg). Ausgeliefert wird NUR die Daten + der leichte Applier/Renderer;
// cubing bleibt devDependency. NICHT von Hand editieren — via `node scripts/gen-puzzle-net.mjs`.
import { getPuzzleGeometryByName } from "cubing/puzzle-geometry";
import { puzzles } from "cubing/puzzles";
import { writeFileSync } from "node:fs";

const round = (s) => s.split(/\s+/).map((x) => (+x).toFixed(1)).join(" ");

async function gen({ constName, pgName, loaderKey, tokens, file }) {
  const pg = getPuzzleGeometryByName(pgName);
  const svg = pg.generatesvg();
  const viewBox = (svg.match(/viewBox="([^"]+)"/) || [])[1] || "0 0 800 500";
  const re = /<polygon id="([A-Za-z0-9]+)-l(\d+)-o(\d+)"[^>]*fill: (#[0-9a-fA-F]+)[^>]*points="([^"]+)"/g;
  const facelets = []; let m;
  while ((m = re.exec(svg))) facelets.push({ o: m[1], p: +m[2], s: +m[3], c: m[4], pts: round(m[5]) });
  const orbitOri = {};
  const kp = await puzzles[loaderKey].kpuzzle();
  for (const orb of kp.definition.orbits) orbitOri[orb.orbitName] = orb.numOrientations;
  const moves = {};
  for (const t of tokens) {
    const pd = kp.defaultPattern().applyAlg(t).patternData;
    const mv = {};
    for (const orb of Object.keys(pd)) mv[orb] = { pieces: pd[orb].pieces, orientation: pd[orb].orientation };
    moves[t] = mv;
  }
  const data = { viewBox, orbitOri, facelets, moves };
  const out = `// GENERATED by scripts/gen-puzzle-net.mjs (cubing.js oracle) — DO NOT EDIT.\n` +
    `// Facelet-Geometrie + Move-Transforms für ${pgName}. Quelle: cubing ${puzzles[loaderKey].id}.\nexport const ${constName} = ${JSON.stringify(data)} as const;\n`;
  writeFileSync(file, out);
  console.log(`${file}: ${facelets.length} facelets, ${tokens.length} moves, ${(out.length/1024).toFixed(1)}kB`);
}

const pyraTokens = [];
for (const b of ["U","L","R","B","u","l","r","b"]) { pyraTokens.push(b, b + "'"); }
await gen({ constName: "PYRAMINX_NET", pgName: "pyraminx", loaderKey: "pyraminx", tokens: pyraTokens, file: "src/lib/puzzle-net-data/pyraminx.ts" });
